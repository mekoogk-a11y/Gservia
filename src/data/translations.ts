export const getTranslation = (lang: Language): TranslationDictionary => {
  return translations[lang] || translations.en;
};

export const detectDeviceLanguage = (): Language => {
  try {
    const browserLangs = navigator.languages || [navigator.language];
    for (const l of browserLangs) {
      const prefix = l.split('-')[0].toLowerCase() as Language;
      if (SUPPORTED_LANGUAGES.some((item) => item.code === prefix)) {
        return prefix;
      }
    }
  } catch {
    // fallback
  }
  return 'ar';
};
