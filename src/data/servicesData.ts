// Helper search function to resolve natural language and metadata
export function findServicesByQuery(query: string, lang: 'ar' | 'en' = 'ar'): GlobalService[] {
  if (!query || !query.trim()) return GLOBAL_SERVICES;
  const q = query.toLowerCase().trim();

  return GLOBAL_SERVICES.filter(s => {
    const matchName = s.name.toLowerCase().includes(q) || (s.nameAr && s.nameAr.includes(q));
    const matchDesc = s.description.toLowerCase().includes(q) || s.descriptionAr.includes(q);
    const matchShort = s.shortDescription.toLowerCase().includes(q) || s.shortDescriptionAr.includes(q);
    const matchCat = s.categoryId.toLowerCase().includes(q);
    const matchFeatures = s.features.some(f => f.toLowerCase().includes(q)) || s.featuresAr.some(f => f.includes(q));
    const matchBest = s.bestFor.toLowerCase().includes(q) || s.bestForAr.includes(q);

    return matchName || matchDesc || matchShort || matchCat || matchFeatures || matchBest;
  });
}
